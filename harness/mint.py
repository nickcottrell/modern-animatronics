"""
mint -- reconstruct the essay from coords, and record exactly how.

KEY sentences pass through as their locked slice. STEERED sentences are
generated by the model on the SD card, reached through the MCP gate, from the
prompt built in prompt.py. The output is the drafted essay. The sidecar record,
generations/provenance.json, is the proof of how it was made: which model, the
actual prompts, and the actual text that came back.

The claim, in full: the model named in the record, gated by the SD card and
reached over MCP, produced these sentences from these prompts. Clone the repo,
seat the same model, run this, and you get very close output. Not necessarily
byte-identical (sampling and hardware differ), but the same draft in the same
voice. That closeness is the proof the generation is real.

Run:
  python -m harness.mint --model engine/qwen2.5-14b-touchstone --temp 0.7 --seed 1
"""

import hashlib
import json
import sys
from pathlib import Path

from . import record
from . import prompt as prompt_mod
from . import jeff_bridge


def _sha(text):
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def rebuild_section(section, rendered):
    """Apply STEERED renders to a section, back to front so offsets stay valid."""
    raw = section["raw"]
    edits = []
    for i, sent in enumerate(section["sentences"]):
        if sent["tier"] == record.STEERED and (section["index"], i) in rendered:
            edits.append((sent["start"], sent["end"], rendered[(section["index"], i)]))
    for start, end, text in sorted(edits, reverse=True):
        raw = raw[:start] + text + raw[end:]
    return raw


def mint(repo_root, pins=None, write=True):
    """Return (draft_text, provenance). Calls the model once per STEERED sentence."""
    repo_root = Path(repo_root)
    index, sections = record.load_doc(repo_root)
    voice = record.load_voice(repo_root)
    pins = pins or jeff_bridge.load_pins(repo_root)
    decode = pins.get("decode", {})

    rendered = {}
    generated = []
    for section in sections:
        for i, sent in enumerate(section["sentences"]):
            if sent["tier"] != record.STEERED:
                continue
            system, prompt = prompt_mod.build_prompt(sent, voice, section)
            text, receipt = jeff_bridge.mint_one(pins, system, prompt)
            rendered[(section["index"], i)] = text
            v = receipt.get("verification", {})
            generated.append({
                "section": section["index"],
                "sentence": i,
                "ground": sent.get("ground", ""),
                "system": system,
                "prompt": prompt,
                "output": text,
                "gguf_ok": v.get("gguf_ok"),
                "human_anchor": v.get("human_anchor"),
            })

    draft = "".join(rebuild_section(s, rendered) for s in sections)

    provenance = {
        "model": pins["model_ref"],
        "sd_card": pins.get("gate", {}).get("card"),
        "reached_via": "mcp",
        "decode": {"temperature": decode.get("temperature", 0.0), "seed": decode.get("seed", 0)},
        "source_sha256": index["sha256"],
        "draft_sha256": _sha(draft),
        "note": "re-running this lands very close, not necessarily identical",
        "generated": generated,
    }

    if write:
        gen = repo_root / "generations"
        gen.mkdir(exist_ok=True)
        (gen / "essay.minted.md").write_text(draft)
        (gen / "provenance.json").write_text(json.dumps(provenance, indent=2) + "\n")
    return draft, provenance


def _overrides(argv):
    decode = {}
    if "--temp" in argv:
        decode["temperature"] = float(argv[argv.index("--temp") + 1])
    if "--seed" in argv:
        decode["seed"] = int(argv[argv.index("--seed") + 1])
    model = argv[argv.index("--model") + 1] if "--model" in argv else None
    return model, decode


if __name__ == "__main__":
    root = Path(__file__).resolve().parent.parent
    model, decode = _overrides(sys.argv)
    pins = jeff_bridge.load_pins(root)
    if model:
        pins = {**pins, "model_ref": model}
    if decode:
        pins = {**pins, "decode": {**pins.get("decode", {}), **decode}}
    _draft, prov = mint(root, pins=pins)
    n = len(prov["generated"])
    print("minted -> generations/essay.minted.md (%d generated sentence%s)"
          % (n, "" if n == 1 else "s"), file=sys.stderr)
    print("record -> generations/provenance.json  [model %s, card %s, via mcp]"
          % (prov["model"], prov["sd_card"]), file=sys.stderr)
